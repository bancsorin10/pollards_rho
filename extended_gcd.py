def extended_gcd(a, b):
    if a == 0:
        return b, 0, 1
    else:
        gcd, x, y = extended_gcd(b % a, a)
        return gcd, y - (b//a) * x, x

def geeks(a, b):
    if a == 0:
        return b, 0, 1
    gcd, x1, y1 = geeks(b % a, a)
    x = y1 - (b // a) * x1
    y = x1
    return gcd, x, y

